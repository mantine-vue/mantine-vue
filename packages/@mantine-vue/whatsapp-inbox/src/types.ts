/** One placeholder inside a template component. */
export interface WhatsAppTemplateParameter {
  /**
   * Placeholder key. Positional templates use `1`, `2` and so on; named templates use the
   * variable name. Entered values are stored under this key.
   */
  key: string

  /** Field label. Falls back to the key. */
  label?: string

  /**
   * Value type the placeholder expects.
   * @default 'text'
   */
  type?: WhatsAppTemplateParameterType

  /**
   * Whether a value must be provided before the template can be submitted.
   * @default true
   */
  required?: boolean

  /** Example value from the approved template, shown as a hint. */
  example?: string

  /** Longer explanation shown under the field. */
  description?: string

  /** Input placeholder. Falls back to `example`. */
  placeholder?: string

  /** Largest accepted length, enforced by the parameter form. */
  maxLength?: number
}

/** Header of a template. `format` decides whether it carries text or media. */
export interface WhatsAppTemplateHeaderComponent {
  type: 'header'

  /**
   * What the header renders.
   * @default 'text'
   */
  format?: 'text' | 'image' | 'video' | 'document' | 'location'

  /** Header text with placeholders, for text headers. */
  text?: string

  /** Placeholders inside the header. */
  parameters?: WhatsAppTemplateParameter[]

  /** Media used in the approved example, previewed before the user picks their own. */
  example?: WhatsAppAttachment
}

/** Body of a template. Every template has exactly one. */
export interface WhatsAppTemplateBodyComponent {
  type: 'body'

  /** Body text with placeholders. */
  text: string

  /** Placeholders inside the body. */
  parameters?: WhatsAppTemplateParameter[]
}

/** Static footer of a template. Never carries placeholders. */
export interface WhatsAppTemplateFooterComponent {
  type: 'footer'
  text: string
}

/** A button attached to a template. */
export type WhatsAppTemplateButton =
  | {
      type: 'quick_reply'
      text: string
      /** Payload sent back when the recipient taps the button. */
      payload?: string
    }
  | {
      type: 'url'
      text: string
      /** Target URL, which may end in a placeholder. */
      url: string
      /** Placeholders inside the URL. */
      parameters?: WhatsAppTemplateParameter[]
    }
  | {
      type: 'phone_number'
      text: string
      phoneNumber: string
    }
  | {
      type: 'copy_code'
      text: string
      parameters?: WhatsAppTemplateParameter[]
    }

/** Buttons section of a template. */
export interface WhatsAppTemplateButtonsComponent {
  type: 'buttons'
  buttons: WhatsAppTemplateButton[]
}

/** One section of a template, discriminated by `type`. */
export type WhatsAppTemplateComponent =
  | WhatsAppTemplateHeaderComponent
  | WhatsAppTemplateBodyComponent
  | WhatsAppTemplateFooterComponent
  | WhatsAppTemplateButtonsComponent

/** An approved WhatsApp message template, normalized by the backend. */
export interface WhatsAppTemplate {
  /** Stable identifier. */
  id: string

  /** Template name as registered with the provider. */
  name: string

  /** Language code, for example `en_US`. */
  language: string

  /** Human readable language name. Falls back to `language`. */
  languageLabel?: string

  /** Category badge shown in the selector. */
  category?: WhatsAppTemplateCategory

  /** Approval state. Templates that are not approved are shown as unavailable. */
  status?: WhatsAppTemplateStatus

  /** Sections of the template. */
  components: WhatsAppTemplateComponent[]

  /** Free-form description shown in the selector. */
  description?: string

  /** Anything the consumer needs to carry along. */
  meta?: Record<string, unknown>
}

/**
 * Values entered for a template's placeholders.
 *
 * Records are keyed by `WhatsAppTemplateParameter.key`; `buttons` is keyed by the button index
 * as a string, so the whole object stays JSON serializable.
 */
export interface WhatsAppTemplateValues {
  header?: Record<string, string>
  body?: Record<string, string>
  buttons?: Record<string, Record<string, string>>

  /** Media chosen for a media header. */
  headerMedia?: WhatsAppAttachment | null
}

/** A template as it appears in the history, with its placeholders already resolved. */
export interface WhatsAppTemplateInstance {
  /** Template name as sent. */
  name: string

  /** Language the template was sent in. */
  language?: string

  /** Identifier of the template, when the backend keeps one. */
  templateId?: string

  /** Values the placeholders were filled with. */
  values?: WhatsAppTemplateValues

  /** Full definition, used to render an exact preview of what was sent. */
  template?: WhatsAppTemplate

  /** Pre-rendered body text, used when the definition is no longer available. */
  text?: string
}

