/**
 * State of the WhatsApp customer service window, as reported by the backend.
 *
 * The extension never computes this. WhatsApp's 24-hour rule depends on the provider's own clock
 * and on message events the frontend does not see, so the backend stays authoritative and the
 * components render whatever it says.
 */
export interface WhatsAppMessagingWindow {
  /**
   * Whether free-form messages are currently accepted. `unknown` leaves the composer in its
   * normal state rather than blocking the user on information the backend did not send.
   * @default 'unknown'
   */
  state: 'open' | 'closed' | 'unknown'

  /** Machine readable reason, for consumers that map their own copy onto it. */
  reasonCode?: string

  /** Backend-provided explanation shown to the user when the window is closed. */
  reason?: string

  /** When an open window expires. Shown as a hint in the composer. */
  expiresAt?: WhatsAppTimestamp
}

/**
 * What the consumer allows in a given conversation.
 *
 * Every composer action is driven by these flags. Nothing about WhatsApp's own rules is
 * hard-coded: a provider that does not support list messages simply leaves `interactiveTypes`
 * without `list`, and the editor stops offering it.
 */
export interface WhatsAppConversationCapabilities {
  /**
   * Whether free-form text may be sent. Treated as `false` while the messaging window is
   * closed.
   * @default true
   */
  canSendFreeForm?: boolean

  /**
   * Whether approved templates may be sent. Stays available while the window is closed.
   * @default false
   */
  canSendTemplates?: boolean

  /**
   * Whether media may be attached.
   * @default false
   */
  canSendMedia?: boolean

  /**
   * Whether interactive messages may be composed.
   * @default false
   */
  canSendInteractive?: boolean

  /**
   * Whether the built-in emoji picker may be shown. The `emojiPicker` slot can replace it.
   * @default false
   */
  canUseEmoji?: boolean

  /**
   * Whether a message may be sent as a reply to another one.
   * @default false
   */
  canReplyToMessage?: boolean

  /**
   * Whether failed messages offer a retry action.
   * @default true
   */
  canRetryFailed?: boolean

  /** Media types that may be attached. Defaults to all of them when `canSendMedia` is set. */
  allowedMediaTypes?: WhatsAppMediaType[]

  /** Interactive message types the provider supports. */
  interactiveTypes?: WhatsAppInteractiveType[]

  /** Largest accepted length of a free-form message. */
  maxTextLength?: number

  /** Per media type file constraints, enforced before a file reaches the consumer. */
  mediaConstraints?: Partial<Record<WhatsAppMediaType, WhatsAppMediaConstraints>>

  /** Messaging window state. Drives the closed-window notice. */
  messagingWindow?: WhatsAppMessagingWindow

  /**
   * Explanation shown when the composer is disabled for a reason other than the messaging
   * window, for example a conversation the current agent may not write to.
   */
  disabledReason?: string
}

/**
 * `WhatsAppConversationCapabilities` with every optional flag filled in.
 *
 * Produced by `resolveCapabilities` for use by the composer and related components.
 */
export interface WhatsAppResolvedCapabilities {
  canSendFreeForm: boolean
  canSendTemplates: boolean
  canSendMedia: boolean
  canSendInteractive: boolean
  canUseEmoji: boolean
  canReplyToMessage: boolean
  canRetryFailed: boolean
  allowedMediaTypes: WhatsAppMediaType[]
  interactiveTypes: WhatsAppInteractiveType[]
  maxTextLength: number | undefined
  mediaConstraints: Partial<Record<WhatsAppMediaType, WhatsAppMediaConstraints>>
  messagingWindow: WhatsAppMessagingWindow
  disabledReason: string | undefined

  /** Whether the messaging window explicitly reports itself as closed. */
  windowClosed: boolean

  /** Whether anything at all can be sent right now. */
  canSendAnything: boolean
}

