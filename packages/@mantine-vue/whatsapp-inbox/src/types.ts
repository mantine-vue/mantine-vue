/** A media file that is already hosted somewhere the browser can reach. */
export interface WhatsAppAttachment {
  /** Identifier assigned by the consumer's storage or by the WhatsApp provider. */
  id?: string

  /** Determines which renderer is used. */
  mediaType: WhatsAppMediaType

  /** Location the file is served from. Required to preview or download it. */
  url?: string

  /** Poster for videos, thumbnail for images and documents. */
  thumbnailUrl?: string

  /** Original file name, shown for documents. */
  fileName?: string

  /** MIME type, used for the document icon and for validation. */
  mimeType?: string

  /** Size in bytes. */
  size?: number

  /** Duration in seconds, for audio and video. */
  durationSeconds?: number

  /** Intrinsic width in pixels, used to reserve space before the media loads. */
  width?: number

  /** Intrinsic height in pixels, used to reserve space before the media loads. */
  height?: number

  /** Anything the consumer needs to carry along. */
  meta?: Record<string, unknown>
}

/** Lifecycle of a file picked in the composer. Owned entirely by the consumer. */
export type WhatsAppUploadStatus = 'pending' | 'uploading' | 'uploaded' | 'failed' | 'canceled'

/**
 * One file in the composer, with the upload state the consumer reports back.
 *
 * The extension never uploads anything: it emits `attachmentsAdd` with the picked files and
 * renders whatever `uploads` the consumer passes back in.
 */
export interface WhatsAppUpload {
  /** Identifier generated by the consumer when it accepts the file. */
  id: string

  /** File name shown in the preview. */
  fileName: string

  /** Determines the preview renderer. */
  mediaType: WhatsAppMediaType

  /** Current state of the upload. */
  status: WhatsAppUploadStatus

  /** Progress in percent, `0` to `100`. Rendered as an indeterminate bar when unset. */
  progress?: number

  /** MIME type of the picked file. */
  mimeType?: string

  /** Size in bytes. */
  size?: number

  /** Local or remote preview, typically an object URL. */
  previewUrl?: string

  /** Set once the upload finished. This is what ends up in the outgoing payload. */
  attachment?: WhatsAppAttachment

  /** Human readable failure reason, shown on the preview when `status` is `failed`. */
  error?: string

  /** Anything the consumer needs to carry along. */
  meta?: Record<string, unknown>
}

/** File constraints enforced by the composer before a file reaches the consumer. */
export interface WhatsAppMediaConstraints {
  /** Largest accepted file size in bytes. */
  maxFileSize?: number

  /** Accepted MIME types or extensions, in the format of the `accept` attribute. */
  accept?: string[]

  /** Largest number of files that may be attached to a single message. */
  maxFiles?: number
}

