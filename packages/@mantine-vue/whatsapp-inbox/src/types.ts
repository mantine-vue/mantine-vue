/**
 * Backend neutral domain model of the WhatsApp inbox.
 *
 * These types are independent of Meta Cloud API response shapes. Applications map backend data
 * to this model.
 *
 * Timestamps are plain values so that any serialization survives the trip: ISO 8601 strings are
 * recommended, but anything `new Date(value)` understands is accepted.
 */

/** Point in time accepted by every component. Rendered through the inbox formatters. */
export type WhatsAppTimestamp = string | number | Date

/** Who sent the message. */
export type WhatsAppMessageDirection = 'inbound' | 'outbound'

/**
 * Delivery state of a message, as reported by the backend.
 *
 * Inbound messages usually leave this unset. The extension never advances the state on its own.
 */
export type WhatsAppDeliveryStatus = 'pending' | 'sent' | 'delivered' | 'read' | 'failed'

/** Kind of media carried by an attachment. */
export type WhatsAppMediaType = 'image' | 'video' | 'audio' | 'document' | 'sticker'

/**
 * Discriminator of the message union.
 *
 * `unsupported` is the escape hatch for anything the backend received but could not normalize;
 * rendering it keeps the history complete instead of leaving a hole in it.
 */
export type WhatsAppMessageType =
  | 'text'
  | 'image'
  | 'video'
  | 'audio'
  | 'document'
  | 'sticker'
  | 'location'
  | 'contacts'
  | 'template'
  | 'interactive'
  | 'system'
  | 'unsupported'

